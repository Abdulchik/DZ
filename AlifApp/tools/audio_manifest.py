UI = [
    ("correct", "короткий приятный сигнал — правильный ответ"),
    ("wrong", "мягкий низкий сигнал — неправильный ответ"),
    ("complete", "мелодия завершения урока"),
]


def main():
    rows = []  # (путь, арабский, что произнести)

    for lid, ch, name, tr in LETTERS:
        rows.append(("letters", f"letters/{lid}.mp3", ch, f"название буквы: «{name}»"))

    for lid, ch, name, tr in LETTERS:
        c = CONS[lid]
        for suffix, h, vowel in (("fatha", FATHA, "а"), ("kasra", KASRA, "и"), ("damma", DAMMA, "у")):
            rows.append(("syllables", f"syllables/{lid}_{suffix}.mp3", carrier(lid, ch, h) + h, f"слог «{c}{vowel}»"))
    for lid, ch, name, tr in LETTERS:
        if lid == "alif":
            continue  # сукун на алифе не бывает
        rows.append(("syllables", f"syllables/{lid}_sukun.mp3", "أَ" + ch + SUKUN, f"«а{CONS[lid]}» (согласный с сукуном)"))
    for lid, ch, name, tr in LETTERS:
        c = CONS[lid]
        for suffix, h, vowel in (("fathatan", FATHATAN, "ан"), ("kasratan", KASRATAN, "ин"), ("dammatan", DAMMATAN, "ун")):
            text = carrier(lid, ch, h) + h + ("ا" if h == FATHATAN and lid not in ("alif",) else "")
            rows.append(("syllables", f"syllables/{lid}_{suffix}.mp3", text, f"танвин «{c}{vowel}»"))

    for lid, ch, name, tr in LETTERS:
        c = CONS[lid]
        if lid == "alif":
            madd = [("madd_alif", "آ", "аа"), ("madd_waw", "أُو", "уу"), ("madd_ya", "إِي", "ии")]
        else:
            madd = [("madd_alif", ch + FATHA + "ا", "аа"), ("madd_waw", ch + DAMMA + "و", "уу"),
                    ("madd_ya", ch + KASRA + "ي", "ии")]
        for suffix, text, v in madd:
            rows.append(("madd", f"madd/{lid}_{suffix}.mp3", text, f"долгий слог «{c}{v}» (2 счёта)"))

    for wid, ar, tr, meaning, module in WORDS:
        rows.append(("words", f"words/{wid}.mp3", ar, f"«{tr}» — {meaning} (модуль {module})"))

    for uid, desc in UI:
        rows.append(("ui", f"ui/{uid}.wav", "", desc))

    titles = {
        "letters": "1. Названия букв — `letters/` (модуль 1)",
        "syllables": "2. Слоги с огласовками — `syllables/` (модуль 4)",
        "madd": "3. Долгие слоги (мадд) — `madd/` (модуль 5)",
        "words": "4. Слова — `words/` (модули 4, 6, 7)",
        "ui": "5. Звуки интерфейса — `ui/` (уже есть, сгенерированы скриптом tools/gen_ui_sounds.py)",
    }
    counts = {k: sum(1 for r in rows if r[0] == k) for k in titles}

    out = []
    out.append("# Список аудиофайлов\n")
    out.append("Все файлы кладутся в папку `app/src/main/assets/audio/` с подпапками ниже.")
    out.append("Формат: **MP3** (подходят также **M4A** с диктофона телефона, OGG, WAV), моно, без тишины в начале и конце (≤ 0.2 с).")
    out.append("Расширение в имени может быть любым из этих: `ba.mp3` или `ba.m4a` — приложение найдёт оба.")
    out.append("Запись — голос живого чтеца (не синтез речи). Громкость выровнять по всем файлам.\n")
    out.append("Если файла нет, приложение не упадёт: покажет подсказку «Аудио ещё не добавлено».\n")
    out.append("Список создан скриптом `tools/audio_manifest.py`. Чтобы добавить слово — допишите его в скрипт и запустите заново.\n")
    out.append("## Сводка\n")
    out.append("| Папка | Файлов |\n|---|---|")
    for k in titles:
        out.append(f"| `{k}/` | {counts[k]} |")
    out.append(f"| **Всего** | **{len(rows)}** |\n")
    out.append("Аудио Корана (по аятам) сюда **не** входит — оно скачивается из интернета (EveryAyah.com) и кэшируется.")
    out.append("Примеры таджвида (модуль 8) тоже используют это аудио.\n")

    for k, t in titles.items():
        out.append(f"## {t}\n")
        out.append("| Файл | Текст | Что произнести |\n|---|---|---|")
        for g, path, ar, desc in rows:
            if g == k:
                out.append(f"| `{path}` | {ar} | {desc} |")
        out.append("")

    out.append("## Подсказки для записи\n")
    out.append("- Названия букв (`letters/`) — как учитель произносит название: «алиф», «ба», «та»…")
    out.append("- Слоги — коротко и чётко, одна огласовка: «ба», «би», «бу».")
    out.append("- Танвин с фатхой пишется с алифом на конце (بًا), читается «бан».")
    out.append("- Мадд — гласная тянется ровно в 2 раза дольше короткой.")
    out.append("- Для алифа вместо огласовки звучит хамза: أَ «а», إِ «и», أُ «у».")

    (ROOT / "docs" / "AUDIO_FILES.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    (ROOT / "docs" / "audio_files.txt").write_text("\n".join(r[1] for r in rows) + "\n", encoding="utf-8")
    print(f"Готово: {len(rows)} файлов", counts)


if __name__ == "__main__":
    main()
