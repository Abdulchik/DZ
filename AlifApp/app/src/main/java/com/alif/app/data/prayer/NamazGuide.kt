    /** Простая русская транслитерация из книжной (без знаков долготы): Аллāҳу → Аллаху. */
    fun simplify(t: String): String {
        var s = t.replace("ллāҳ", "ллах").replace("ā", "а").replace("Ā", "А").replace("ō", "а").replace("Ō", "А")
            .replace("ӣ", "и").replace("Ӣ", "И").replace("ӯ", "у").replace("Ӯ", "У")
            .replace("ҳ", "х").replace("Ҳ", "Х").replace("қ", "к").replace("Қ", "К").replace("ъ", "‘")
        s = Normalizer.normalize(s, Normalizer.Form.NFD).filter { Character.getType(it) != Character.NON_SPACING_MARK.toInt() || it == '̆' }
        s = Normalizer.normalize(s, Normalizer.Form.NFC)
        return s.replace("-л-", "-ль-").replace(Regex("(^|\\s)Ал-"), "$1Аль-")
    }
